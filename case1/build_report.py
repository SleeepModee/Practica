"""Create the four-page report from verified analysis outputs."""
from pathlib import Path
from html import escape
import json
import csv

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, KeepTogether

ROOT = Path(__file__).resolve().parent
PDF_PATH = ROOT.parent / "pdf" / "case1_report.pdf"
S = json.loads((ROOT / "summary.json").read_text(encoding="utf-8"))
Q = S["quality"]
with (ROOT / "details" / "thresholds.csv").open(encoding="utf-8-sig", newline="") as f:
    T = {(r["RequestType"], r["ActivityName"]): r for r in csv.DictReader(f)}


def num(x, digits=2):
    return f"{float(x):.{digits}f}".replace(".", ",")


def main():
    # Narrative examples below refer to this supplied dataset, not an arbitrary replacement.
    assert Q["source_sha256"] == "80abaf9340affdfc31848603e12df595f8cce8e70a87238bae5b25401baacf0e", "The report examples require the original Case 1 source"
    assert (S["finding_rows"], S["candidate_processes"], S["behavior_processes"], Q["events_at_cutoff"]) == (90, 82, 72, 12137)
    # Arial ships with Windows; an alternative font directory may be supplied by editing this setting.
    fonts = Path("C:/Windows/Fonts")
    pdfmetrics.registerFont(TTFont("CaseArial", str(fonts / "arial.ttf")))
    pdfmetrics.registerFont(TTFont("CaseArialBold", str(fonts / "arialbd.ttf")))
    pdfmetrics.registerFontFamily("CaseArial", normal="CaseArial", bold="CaseArialBold")
    styles = {
        "title": ParagraphStyle("title", fontName="CaseArialBold", fontSize=21, leading=25, textColor=colors.HexColor("#173A56"), spaceAfter=12),
        "h1": ParagraphStyle("h1", fontName="CaseArialBold", fontSize=14, leading=18, textColor=colors.HexColor("#173A56"), spaceBefore=9, spaceAfter=8),
        "h2": ParagraphStyle("h2", fontName="CaseArialBold", fontSize=10.5, leading=14, spaceBefore=7, spaceAfter=4),
        "body": ParagraphStyle("body", fontName="CaseArial", fontSize=10, leading=13.6, spaceAfter=7),
        "small": ParagraphStyle("small", fontName="CaseArial", fontSize=8.8, leading=11.5, spaceAfter=5),
        "table": ParagraphStyle("table", fontName="CaseArial", fontSize=9, leading=11.8),
        "th": ParagraphStyle("th", fontName="CaseArialBold", fontSize=9, leading=11.8, textColor=colors.white),
    }
    story, md = [], []

    def para(text, style="body"):
        story.append(Paragraph(escape(text), styles[style]))
        prefix = {"title": "# ", "h1": "## ", "h2": "### "}.get(style, "")
        md.append(prefix + text + "\n")

    def table(headers, rows, widths):
        values = [[Paragraph(escape(str(x)), styles["th"]) for x in headers]]
        values += [[Paragraph(escape(str(x)), styles["table"]) for x in r] for r in rows]
        tab = Table(values, colWidths=widths, repeatRows=1, hAlign="LEFT")
        tab.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#234F6D")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 7), ("RIGHTPADDING", (0, 0), (-1, -1), 7),
            ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#EFF4F7"), colors.white]),
            ("LINEBELOW", (0, 0), (-1, 0), .5, colors.HexColor("#234F6D")),
            ("LINEBELOW", (0, 1), (-1, -1), .35, colors.HexColor("#D7E0E6")),
        ]))
        story.extend([tab, Spacer(1, 8)])
        md.append("| " + " | ".join(headers) + " |")
        md.append("| " + " | ".join("---" for _ in headers) + " |")
        md.extend("| " + " | ".join(str(x) for x in r) + " |" for r in rows)
        md.append("")

    def page():
        story.append(PageBreak())
        md.append("\n---\n")

    para("Анализ заявок на закупку", "title")
    para("Кейс 1. Поиск нетипичного поведения по журналу событий", "small")
    para("1. Данные и граница наблюдения", "h1")
    para("Исследованы students.csv, task.md, dataset_description.md и submission_template.md. "
         "Синтетический журнал содержит 12 162 события по 1 000 заявкам: standard - 635, contract - 197, urgent - 168. "
         "Единица анализа - экземпляр ProcessInstanceId; задания связаны по TaskId. Использованы Python, pandas и NumPy.")
    para("Обнаружено противоречие описанию: в исходном файле 25 событий по 10 заявкам имеют время позже заявленного среза "
         "01.07.2026 00:00 UTC+03:00; последнее событие - 01.07.2026 17:59:57. "
         "Основной анализ ограничен заявленным срезом. Исходный файл не изменён; поздние события вынесены в отдельную таблицу "
         "и отмечены как качество выгрузки, а не нарушение закупки.")
    table(["Показатель", "На заявленный срез"], [
        ["События / заявки", "12 137 / 1 000"],
        ["Завершены / успешны / отклонены", "980 / 929 / 51"],
        ["Открытые процессы / открытые задания", "20 / 19"],
        ["Закрытые человеческие задания", "4 569"],
    ], [320, 191])
    para("Один открытый процесс находится между заданиями; будущий этап ещё не создан. Во всём исходном файле завершений 990, "
         "но 10 из них относятся к времени после среза. Это объясняет различие счётчиков.")
    para("2. Обычное поведение и качество", "h1")
    para("Успешная заявка проходит проверку специалистом, согласование руководителем, бюджет у финансиста и исполнение закупщиком. "
         "Для contract перед исполнением обязательна юридическая проверка. Возврат руководителя ведёт через доработку заявителем, "
         "повторную проверку и новое решение руководителя. Отказ руководителя завершает процесс с rejected.")
    para("Прямой успешный маршрут без возвратов наблюдается у 490 standard, 133 urgent и 148 contract заявок - всего 771 (77,1%). "
         "Это частота последовательности этапов, а не гарантия отсутствия временных или ролевых отклонений. "
         "У 873 заявок нет возвратов, у 119 один, у 8 от пяти до восьми.")
    para("Не найдены дубли EventId и строк, разрывы/повторы EventIndex, обратный ход времени, изменение типа/суммы/версии внутри заявки "
         "и несовместимые статусы событий. Проверены связи создания и закрытия заданий. Ожидаемые пустые исполнители технических событий "
         "не считаются ошибкой. Повтор ActivityId с новым TaskId сохраняется.", "small")

    page()
    para("3. Воспроизводимый метод и критерии", "h1")
    para("События прочитаны как UTF-8 с BOM, разделитель - запятая. EventIndex преобразован в число; "
         "внутри заявки сортировка выполняется по нему. Даты приведены к UTC+03:00. После проверки качества отобраны события не позже среза. "
         "Длительность закрытого задания - разность дат закрытия и создания с тем же TaskId.")
    para("Календарные часы считаются без исключений. Рабочие часы - пересечение интервала с понедельником-пятницей, 09:00-18:00, "
         "без праздников и обеда, согласно описанию. Для открытого задания рассчитан только его возраст до среза; "
         "в статистику закрытых заданий такие интервалы не включены.")
    para("Медианы закрытых заданий, рабочие часы", "h2")
    stages = ["Проверка заявки", "Согласование руководителем", "Согласование бюджета", "Проверка договора", "Исполнение заявки", "Доработка заявки"]
    baseline = [[a, *[num(T[typ, a]["MedianWorkHours"]) if (typ, a) in T else "-" for typ in ["standard", "urgent", "contract"]]] for a in stages]
    table(["Этап", "standard", "urgent", "contract"], baseline, [235, 92, 92, 92])
    para("Срочные заявки заметно быстрее, поэтому единый порог для всех типов был бы некорректен. "
         "Сравнения выполнены отдельно для каждого сочетания RequestType и этапа; повторы заданий входят отдельными наблюдениями.")
    para("Статистические границы", "h2")
    para("Для групп минимум из 20 закрытых заданий взяты квартильные границы логарифма рабочих часов: "
         "L1 = Q25(ln t), L3 = Q75(ln t), D = L3 - L1, m = медиана t. "
         "Верхняя граница U = max(exp(L3 + 3D), 4m), нижняя L = min(exp(L1 - 3D), 0,1m). "
         "Логарифм учитывает асимметрию положительных длительностей, а внешние границы и ограничения по медиане уменьшают случайные срабатывания.")
    para("Закрытое задание отмечается при t > U. Для быстрого исполнения нужно минимум два человеческих задания одной заявки с t < L. "
         "Открытое задание отмечается, только если его уже накопленный возраст > U. Для повторных возвратов принят консервативный "
         "критерий не менее трёх; это признак для анализа причин, а не установленный бизнес-запрет.")
    para("Структурные критерии: отсутствие обязательного этапа у успешно завершённой заявки; создание этапа до принятия обязательной "
         "предшествующей проверки; роль исполнителя вне ожидаемой; повторная проверка без предусмотренного возврата и доработки. "
         "Внеплановые проверки auditor не исключаются из истории, но по одной редкости аномалиями не объявляются.")
    para("Все квартильные значения, объёмы групп и границы сохранены в details/thresholds.csv. "
         "Параметры применены одинаково ко всем заявкам; идентификаторы подозрительных заявок в правила не зашиты.", "small")

    page()
    para("4. Результаты и проверяемые примеры", "h1")
    para("В anomalies.csv 90 строк по 82 различным заявкам (8,2% журнала). Из них 80 строк по 72 заявкам относятся к поведению, "
         "10 строк по 10 другим заявкам - к событиям после среза. Структурные признаки встречаются у 40 заявок, статистические у 40; "
         "пересечение - 8 заявок с пропуском руководителя и долгой первичной проверкой. Поэтому числа строк нельзя складывать как число заявок.")
    table(["Тип наблюдения", "Строк / заявок", "Характер вывода"], [
        ["Пропуск обязательного этапа", "16 / 16", "Отклонение от заданной схемы"],
        ["Нарушение порядка", "8 / 8", "Отклонение от заданной схемы"],
        ["Несоответствие роли", "8 / 8", "Проверка полномочий"],
        ["Повтор без возврата", "8 / 8", "Необъяснённое повторение этапа"],
        ["Длительное задание", "16 / 16", "Статистический кандидат"],
        ["Слишком быстрые задания", "8 / 8", "Статистический кандидат"],
        ["Длительное ожидание", "8 / 8", "Возраст открытого задания"],
        ["Частые возвраты", "8 / 8", "Разбор причин доработок"],
        ["События после среза", "10 / 10", "Качество выгрузки"],
    ], [215, 90, 206])
    para("Пример 1. Пропуск и задержка одновременно", "h2")
    para("ProcessInstanceId: 17b4a994-a650-5539-979c-114b14dc20d6", "small")
    para("Срочная заявка успешно завершена без согласования руководителем. Проверка заявки длилась с 23.04.2026 15:39:41 "
         "до 04.05.2026 12:39:41: 60 рабочих и 261 календарный час. Медиана проверки urgent - 0,137 ч, верхняя граница - 0,949 ч. "
         "Длительность примерно в 437 раз больше медианы. Два самостоятельных основания записаны двумя строками.")
    para("Пример 2. Исполнение до бюджета", "h2")
    para("ProcessInstanceId: 06dc4973-ce2e-59c5-b252-aa7f1eb62270", "small")
    para("«Исполнение заявки» создано 05.03.2026 13:12:14 (EventIndex 7), тогда как бюджет согласован только в 17:27:20 "
         "(EventIndex 10). Вывод основан на времени создания исполнения, поэтому не сводится к случайной разнице дат закрытия.")
    para("Пример 3. Неподходящая роль", "h2")
    para("ProcessInstanceId: 35097b8a-4b7a-5efa-9645-b3d552458029", "small")
    para("Задание «Согласование руководителем» закрыто с ролью requester вместо manager (EventIndex 6). Всего таких заявок восемь. "
         "Только в двух из них исполнитель также совпадает с инициатором; остальные шесть не называются самосогласованием.")

    page()
    para("5. Временные отклонения и ограничения", "h1")
    para("Пример 4. Задания закрыты за секунды", "h2")
    para("ProcessInstanceId: 26b4c1f5-fe6b-540d-a343-ae6aac25f87f", "small")
    para("Проверка, руководитель, бюджет и исполнение заняли 9, 8, 19 и 7 секунд соответственно. Медианы соответствующих "
         "этапов standard - около 1 432, 7 207, 9 358 и 17 682 секунд. По всем восьми быстрым заявкам выделено 31 задание "
         "с длительностью 6-20 секунд. Это повод проверить способ закрытия, но не доказательство фиктивной работы.")
    para("Пример 5. Длительное открытое задание", "h2")
    para("ProcessInstanceId: 363974d3-8b55-58e7-a74e-7f3b5ec0a6b7", "small")
    para("Согласование руководителем создано 26.01.2026 10:32:11 и не закрыто к срезу. Накоплено не менее 1 006,464 рабочих часов "
         "при верхней границе standard 18,085 ч. Всего таких старых заданий восемь; 12 остальных открытых процессов не объявлены зависшими.")
    para("Что проверено и что требует осторожности", "h2")
    para("Из 16 долгих проверок восемь длятся 8 рабочих часов, восемь - 60. При изменении множителя логарифмического межквартильного "
         "размаха с 3 до 2,5 или 3,5 сохраняются те же 16 долгих, 8 быстрых и 8 старых открытых заявок. "
         "Расчёт рабочих часов для всех 4 588 заданий независимо проверен посуточным пересечением интервалов; расхождение менее 10^-8 часа.")
    para("В details/manual_review.csv вынесены восемь заявок с двумя внеплановыми проверками каждая. Их бизнес-основание из журнала "
         "неизвестно. Допустимая роль auditor и редкость сами по себе не означают нарушение. Также не считаются ошибкой единичный возврат, "
         "выходные, законный отказ и высокая сумма заявки без дополнительных оснований.")
    para("Длительность задания включает ожидание, а не только труд исполнителя. SLA и разрешения на исключения не заданы; "
         "статистические кандидаты требуют проверки контекста. Эталонной разметки нет, поэтому полнота и точность в процентах не заявляются. "
         "Десять проблем с границей выгрузки следует уточнить у владельца данных. Для ещё не созданного задания длительность не оценивается.")
    para("6. Воспроизводимость и использование AI", "h1")
    para("В комплект входят код analyze_case1.py, build_report.py, README.md, requirements.txt и таблицы доказательств. "
         "Версии при проверке: Python 3.12.14, pandas 3.0.1, NumPy 2.3.5. SHA-256 источника и проверки сохранены в summary.json. "
         "CSV соответствует точным трём заголовкам шаблона; все ProcessInstanceId существуют, одинаковых строк нет.")
    para("AI использован для разбора задания, разработки кода и критериев, интерпретации и подготовки отчёта. Ответы проверены "
         "программным выполнением на исходном CSV, сверкой последовательностей и идентификаторов, независимым расчётом рабочего времени "
         "и анализом чувствительности порогов. Результаты AI не используются вместо доказательств из журнала.")

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setStrokeColor(colors.HexColor("#CDD8DF"))
        canvas.line(42, 35, A4[0]-42, 35)
        canvas.setFont("CaseArial", 8)
        canvas.setFillColor(colors.HexColor("#536777"))
        canvas.drawString(42, 23, "Кейс 1 | Анализ журнала закупок | Срез: 01.07.2026 00:00 +03:00")
        canvas.drawRightString(A4[0]-42, 23, str(doc.page))
        canvas.restoreState()

    PDF_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(str(PDF_PATH), pagesize=A4, rightMargin=42, leftMargin=42, topMargin=40, bottomMargin=46,
                            title="Кейс 1. Анализ заявок на закупку", author="Аналитическая работа по производственной практике")
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    (ROOT / "report.md").write_text("\n".join(md), encoding="utf-8")
    print(PDF_PATH)


if __name__ == "__main__":
    main()
